def _verdicts(sentences, rows):
    return [claim(t, v, why, risk) for t, (v, why, risk) in zip(sentences, rows)]


def new_sample(id, group, name, sentences, reference, rows, truth_note, error=None):
    """error = (誤りの種類, 誤りの文の番号, 直した文)。誤りのある見本は、直した本文と、直した後の模擬の応答（すべて一致）も持つ。"""
    sample = dict(id=id, group=group, name=name, body="".join(sentences), reference=reference, truth_note=truth_note, errors=[],
                  judge=judged(*_verdicts(sentences, rows)))
    if error:
        kind, index, fixed = error
        sample["errors"] = [{"type": kind, "claim": sentences[index]}]
        after = list(sentences)
        after[index] = fixed
        sample["fixed_body"] = "".join(after)
        sample["judge_after"] = judged(*_verdicts(after, [("consistent", "要点と一致する", "high" if i == index else "low") for i in range(len(after))]))
    N.append(sample)


